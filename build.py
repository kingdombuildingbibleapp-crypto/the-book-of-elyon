"""Build the static site's data from elyon-data-v1.json.

Usage: python3 build.py [path/to/elyon-data-v1.json]
Writes public/data/index.json (book list + translations) and
public/data/books/<ID>.json (one file per book).
"""
import json, os, sys, shutil

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "data", "elyon-data-v1.json")
d = json.load(open(src, encoding="utf-8"))

out = os.path.join(here, "public", "data")
shutil.rmtree(out, ignore_errors=True)
os.makedirs(os.path.join(out, "books"))

index = {k: d[k] for k in ("title", "version", "text", "translations")}
index["books"] = []
base_note = ""  # notes reading "Same" refer to the previous book's source; spell it out for readers
page = 1  # continuous page numbering: one page per chapter of each book's first translation
for b in d["books"]:
    meta = {k: v for k, v in b.items() if k != "translations"}
    meta["translations"] = {k: len(v["chapters"]) for k, v in b["translations"].items()}
    note = meta.get("dateNote") or ""
    if note.lower().startswith("same") and base_note:
        meta["dateNote"] = base_note + note[4:]
    else:
        base_note = note
    meta["page"] = page
    page += next(iter(meta["translations"].values()))
    index["books"].append(meta)
    with open(os.path.join(out, "books", b["id"] + ".json"), "w", encoding="utf-8") as f:
        json.dump(b["translations"], f, ensure_ascii=False, separators=(",", ":"))
index["pages"] = page - 1
with open(os.path.join(out, "index.json"), "w", encoding="utf-8") as f:
    json.dump(index, f, ensure_ascii=False, separators=(",", ":"))
print(f"built {len(index['books'])} books, {index['pages']} pages -> {out}")

# ---------------------------------------------------------------- study plans
# Each plan is a list of books read in Elyon's order, split into days of
# roughly equal length (by verse count, whole chapters only).
PLANS = [
    ("elyon-year", "Through Elyon in a Year", "Every book, in the order it was written: a thousand years of scripture in 365 days.", None, 365),
    ("gospels-30", "The Four Gospels", "The life and teaching of Jesus in Mark, Matthew, Luke and John.", ["MAR", "MAT", "LUK", "JOH"], 30),
    ("torah-40", "The Torah in 40 Days", "Genesis to Deuteronomy, the five books of Moses.", ["GEN", "EXO", "LEV", "NUM", "DEU"], 40),
    ("psalms-proverbs-31", "Psalms and Proverbs", "A month of prayer, praise and wisdom.", ["PSA", "PRO"], 31),
    ("prophets-60", "The Prophets", "Isaiah to Malachi, the voices that called Israel back to God.",
     ["HOS", "AMO", "ISA", "ZEP", "NAH", "JOE", "JER", "HAB", "HAG", "LAM", "OBA", "EZE", "ZEC", "MIC", "MAL", "JON", "DAN"], 60),
    ("wisdom-30", "The Wisdom Books", "Job, Ecclesiastes, the Song of Songs, Wisdom of Solomon and Sirach.", ["JOB", "ECC", "SOL", "WIS", "SIR"], 30),
    ("enoch-jubilees-21", "Enoch and Jubilees", "The two great books of the Second Temple period, beyond the usual canon.", ["1EN", "JUB"], 21),
    ("paul-30", "The Letters of Paul", "Paul's letters, from 1 Thessalonians to Titus.",
     ["1TH", "GAL", "1CO", "2CO", "ROM", "PHM", "PHI", "2TH", "COL", "EPH", "1TI", "2TI", "TIT"], 30),
]
by_id = {b["id"]: b for b in d["books"]}
plans = []
for pid, name, about, ids, ndays in PLANS:
    ids = ids or [b["id"] for b in d["books"]]
    chapters = []  # (bookId, chapter, verses)
    for bid in ids:
        first = next(iter(by_id[bid]["translations"].values()))["chapters"]
        chapters += [(bid, i + 1, max(1, len(c))) for i, c in enumerate(first)]
    total = sum(c[2] for c in chapters)
    days, cur, acc = [], [], 0
    for i, (bid, ch, n) in enumerate(chapters):
        cur.append((bid, ch))
        acc += n
        left_days = ndays - len(days) - 1
        left_ch = len(chapters) - i - 1
        if left_days > 0 and (acc >= total * (len(days) + 1) / ndays or left_ch <= left_days - 0):
            days.append(cur); cur = []
    if cur:
        days.append(cur)
    assert len(days) == ndays, (pid, len(days))
    # compress each day into book ranges: [[bookId, fromCh, toCh], ...]
    readings = []
    for day in days:
        r = []
        for bid, ch in day:
            if r and r[-1][0] == bid and r[-1][2] == ch - 1:
                r[-1][2] = ch
            else:
                r.append([bid, ch, ch])
        readings.append(r)
    plans.append({"id": pid, "name": name, "about": about, "days": readings})
with open(os.path.join(out, "plans.json"), "w", encoding="utf-8") as f:
    json.dump(plans, f, ensure_ascii=False, separators=(",", ":"))
cat = os.path.join(here, "convex", "planCatalog.ts")
with open(cat, "w", encoding="utf-8") as f:
    f.write("// Generated by build.py from the study plans there. Do not edit by hand.\n")
    f.write("// The number of days in each study plan, used to check plan progress.\n")
    f.write("export const PLAN_DAYS: Record<string, number> = {\n")
    for p in plans:
        f.write(f'  "{p["id"]}": {len(p["days"])},\n')
    f.write("};\n")
print(f"built {len(plans)} study plans")
